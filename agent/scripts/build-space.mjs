/**
 * Builds the Hugging Face Space for the agent (docs/agent-plan.md §3).
 *
 * Output: agent/space/ with exactly four files — server.mjs (our code and
 * @fpl/shared, bundled), package.json (only the Agent SDK and zod, installed
 * in the image so the SDK gets its native Claude Code binary), Dockerfile and
 * the Space README. Nothing else from this private repo is ever uploaded.
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const out = path.join(root, "space");
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

await build({
  entryPoints: [path.join(root, "src/server.ts")],
  outfile: path.join(out, "server.mjs"),
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  // Installed in the image: the SDK needs its platform binary, and zod must be
  // the same instance the SDK uses to read our tool schemas.
  external: ["@anthropic-ai/claude-agent-sdk", "zod"],
  banner: { js: "// Gameweek Copilot agent — generated by agent/scripts/build-space.mjs. Do not edit." },
  legalComments: "none",
});

writeFileSync(
  path.join(out, "package.json"),
  `${JSON.stringify(
    {
      name: "gameweek-copilot-agent",
      private: true,
      type: "module",
      engines: { node: ">=22" },
      dependencies: {
        "@anthropic-ai/claude-agent-sdk": pkg.dependencies["@anthropic-ai/claude-agent-sdk"],
        zod: pkg.dependencies.zod,
      },
    },
    null,
    2,
  )}\n`,
);

writeFileSync(
  path.join(out, "Dockerfile"),
  `FROM node:22-bookworm-slim

# Hugging Face runs Spaces as uid 1000, which is the image's "node" user.
WORKDIR /app
COPY --chown=node:node package.json ./
RUN npm install --omit=dev --no-audit --no-fund && npm cache clean --force
COPY --chown=node:node server.mjs ./

USER node
ENV NODE_ENV=production PORT=7860 HOME=/tmp
EXPOSE 7860
CMD ["node", "server.mjs"]
`,
);

writeFileSync(
  path.join(out, "README.md"),
  `---
title: Gameweek Copilot Agent
emoji: ⚽
colorFrom: green
colorTo: gray
sdk: docker
app_port: 7860
pinned: false
---

The agent service behind Gameweek Copilot: the Claude Agent SDK with every
built-in tool removed and only read-only Fantasy Premier League tools.

It only answers requests that carry the website's shared secret. \`GET /health\`
shows whether it is up. Secrets (set in Settings → Variables and secrets):
\`ANTHROPIC_API_KEY\`, \`AGENT_SHARED_SECRET\`, \`SUPABASE_URL\`,
\`SUPABASE_PUBLISHABLE_KEY\`.
`,
);

console.log(`Space built in ${path.relative(process.cwd(), out) || out}: server.mjs, package.json, Dockerfile, README.md`);
